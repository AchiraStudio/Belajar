-- 7. Role Grants & Privilege Revocation
GRANT SELECT, INSERT, UPDATE, DELETE ON opportunities, tracked_opportunities, peer_profiles TO belajar_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO belajar_app;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON opportunities, tracked_opportunities, peer_profiles FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON opportunities, tracked_opportunities, peer_profiles FROM authenticated;
  END IF;
END $$;
