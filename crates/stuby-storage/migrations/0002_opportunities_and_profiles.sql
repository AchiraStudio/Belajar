--   * R2: Save-to-Track Lifecycle (Saved -> Applied -> Done with reminders)
--   * R3: Peer Profiles & Teammate Matching (major, skills, interests, availability)
--   * R4: Guidelines Study Pipeline Integration (documents.opportunity_id)
--   * R5: Database Schema & Migration (PostgreSQL / Supabase with RLS)

-- 1. Extend app_users with role and admin flags
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'student';
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS is_admin integer NOT NULL DEFAULT 0;

-- Update existing default owner to admin
UPDATE app_users SET role = 'admin', is_admin = 1 WHERE label = 'owner';

-- Auto-assign admin status for any future rows inserted with label = 'owner'
CREATE OR REPLACE FUNCTION set_owner_admin() RETURNS trigger AS $$
BEGIN
  IF NEW.label = 'owner' THEN
    NEW.role := 'admin';
    NEW.is_admin := 1;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_app_users_owner_admin ON app_users;
CREATE TRIGGER trg_app_users_owner_admin
BEFORE INSERT OR UPDATE ON app_users
FOR EACH ROW
EXECUTE FUNCTION set_owner_admin();

-- 2. Opportunities Table (R1)
CREATE TABLE opportunities (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creator_id     uuid DEFAULT NULLIF(current_setting('app.user_id', true), '')::uuid REFERENCES app_users(id) ON DELETE SET NULL,
  title          text NOT NULL,
  description    text NOT NULL,
  category       text NOT NULL, -- 'competition' | 'scholarship'
  organizer      text NOT NULL,
  deadline       double precision NOT NULL, -- epoch seconds
  reward         text,
  target_majors  jsonb NOT NULL DEFAULT '[]'::jsonb,
  eligibility    text,
  website_url    text,
  guideline_url  text,
  guideline_text text,
  is_published   integer NOT NULL DEFAULT 1,
  created_at     double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  updated_at     double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  CONSTRAINT chk_opportunities_category CHECK (category IN ('competition', 'scholarship')),
  CONSTRAINT chk_opportunities_published CHECK (is_published IN (0, 1))
);

CREATE INDEX idx_opportunities_category ON opportunities(category);
CREATE INDEX idx_opportunities_deadline ON opportunities(deadline);
CREATE INDEX idx_opportunities_published ON opportunities(is_published);
CREATE INDEX idx_opportunities_target_majors ON opportunities USING gin(target_majors);

-- 3. Tracked Opportunities Table (R2)
CREATE TABLE tracked_opportunities (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        uuid NOT NULL DEFAULT NULLIF(current_setting('app.user_id', true), '')::uuid REFERENCES app_users(id) ON DELETE CASCADE,
  opportunity_id bigint NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  status         text NOT NULL DEFAULT 'Saved', -- 'Saved' | 'Applied' | 'Done'
  notes          text,
  created_at     double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  updated_at     double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  applied_at     double precision,
  completed_at   double precision,
  CONSTRAINT uq_tracked_user_opportunity UNIQUE (user_id, opportunity_id),
  CONSTRAINT chk_tracked_status CHECK (status IN ('Saved', 'Applied', 'Done'))
);

CREATE INDEX idx_tracked_user ON tracked_opportunities(user_id);
CREATE INDEX idx_tracked_opportunity ON tracked_opportunities(opportunity_id);
CREATE INDEX idx_tracked_status ON tracked_opportunities(user_id, status);

-- 4. Peer Profiles Table (R3)
CREATE TABLE peer_profiles (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             uuid NOT NULL UNIQUE DEFAULT NULLIF(current_setting('app.user_id', true), '')::uuid REFERENCES app_users(id) ON DELETE CASCADE,
  full_name           text NOT NULL,
  major               text NOT NULL,
  batch_year          integer,
  bio                 text,
  academic_interests  jsonb NOT NULL DEFAULT '[]'::jsonb,
  skills              jsonb NOT NULL DEFAULT '[]'::jsonb,
  contact_info        jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_looking_for_team integer NOT NULL DEFAULT 1,
  created_at          double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  updated_at          double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp()),
  CONSTRAINT chk_peer_looking CHECK (is_looking_for_team IN (0, 1))
);

CREATE INDEX idx_profiles_user ON peer_profiles(user_id);
CREATE INDEX idx_profiles_major ON peer_profiles(major);
CREATE INDEX idx_profiles_looking ON peer_profiles(is_looking_for_team);
CREATE INDEX idx_profiles_skills ON peer_profiles USING gin(skills);
CREATE INDEX idx_profiles_interests ON peer_profiles USING gin(academic_interests);

-- 5. Extend Documents with optional Opportunity Link (R4)
ALTER TABLE documents ADD COLUMN IF NOT EXISTS opportunity_id bigint REFERENCES opportunities(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_documents_opportunity ON documents(opportunity_id);

-- 6. Row-Level Security
-- Public tables must have FORCE ROW LEVEL SECURITY enabled to pass postgres.rs verification
ALTER TABLE opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE opportunities FORCE ROW LEVEL SECURITY;

CREATE POLICY opportunities_select ON opportunities FOR SELECT
  USING (
    is_published = 1
    OR (
      NULLIF(current_setting('app.user_id', true), '') IS NOT NULL
      AND (
        creator_id = NULLIF(current_setting('app.user_id', true), '')::uuid
        OR EXISTS (
          SELECT 1 FROM app_users
          WHERE id = NULLIF(current_setting('app.user_id', true), '')::uuid
            AND is_admin = 1
        )
      )
    )
  );

CREATE POLICY opportunities_insert ON opportunities FOR INSERT
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM app_users
      WHERE id = NULLIF(current_setting('app.user_id', true), '')::uuid
        AND is_admin = 1
    )
  );

CREATE POLICY opportunities_update ON opportunities FOR UPDATE
  USING (
    EXISTS (
      SELECT 1 FROM app_users
      WHERE id = NULLIF(current_setting('app.user_id', true), '')::uuid
        AND is_admin = 1
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM app_users
      WHERE id = NULLIF(current_setting('app.user_id', true), '')::uuid
        AND is_admin = 1
    )
  );

CREATE POLICY opportunities_delete ON opportunities FOR DELETE
  USING (
    EXISTS (
      SELECT 1 FROM app_users
      WHERE id = NULLIF(current_setting('app.user_id', true), '')::uuid
        AND is_admin = 1
    )
  );

-- Tracked opportunities: per-student owner isolation
ALTER TABLE tracked_opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE tracked_opportunities FORCE ROW LEVEL SECURITY;

