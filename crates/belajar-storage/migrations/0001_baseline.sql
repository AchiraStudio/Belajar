  text        text NOT NULL,
  note_md     text,
  tsv         tsvector GENERATED ALWAYS AS (
                setweight(to_tsvector('indonesian', coalesce(label, '')), 'B') ||
                setweight(to_tsvector('indonesian', text), 'A')) STORED
);
