-- Belajar baseline schema for PostgreSQL (Supabase target).
-- Translated from the legacy SQLite schema v3 (db.py), with deliberate changes:
--   * every table has user_id (multi-user ready) and row-level security keyed to the session
--     variable `app.user_id`; the database, not application discipline, isolates owners;
--   * ids are bigint identity (ids from a legacy database are preserved by the ETL);
--   * JSON stored as TEXT in SQLite is jsonb here;
--   * instants stay `double precision` epoch seconds and days stay ISO `text` — the API contract
--     of the unchanged frontend depends on those shapes (docs/MIGRATION_PLAN.md ADR-11 rev. 3);
--   * integer 0/1 flags stay integers for the same reason;
--   * SQLite FTS5 is replaced by a generated tsvector + GIN index (retrieval parity: R-D3).

CREATE TABLE app_users (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  label      text NOT NULL DEFAULT 'owner',
  created_at double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM clock_timestamp())
);

-- Server-side login sessions (token stored hashed). Not row-secured: looked up before the owner is
-- known. The cookie value never equals the stored hash.
CREATE TABLE sessions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  created_at double precision NOT NULL,
  expires_at double precision NOT NULL,
  user_agent text
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

