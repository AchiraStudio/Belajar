-- ---------------------------------------------------------------- row-level security
-- Deny by default: a row is visible/writable only when its user_id equals the session variable
-- `app.user_id`. FORCE applies the policy to the table owner too. Superusers and roles with
-- BYPASSRLS (Supabase's `postgres`) still bypass it, so the server must connect as a dedicated
-- role without those attributes (scripts/db/create_app_role.sql).
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'subjects','documents','chunks','notes','quizzes','questions','attempts','answers',
    'study_events','jobs','settings','chat_sessions','chat_messages','ask_sessions','player',
    'achievements','concepts','cards','game_runs','game_turns','mastery','evidence','quests','mindmaps'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY owner_isolation ON %I
        USING (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid)
        WITH CHECK (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid)$p$, t);
  END LOOP;
END $$;

-- Auth tables: RLS on, and a policy only for the server role. Nothing else can read them.
ALTER TABLE app_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY server_only ON app_users TO belajar_app USING (true) WITH CHECK (true);
CREATE POLICY server_only ON sessions  TO belajar_app USING (true) WITH CHECK (true);

-- The server role (created by scripts/db/create_app_role.sql BEFORE this migration) gets plain DML.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO belajar_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO belajar_app;

-- Supabase grants new public tables to its API roles by default. Belajar never uses the Data API,
-- so take those privileges away as a second layer behind RLS (no-op on a plain Postgres).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
  END IF;
END $$;
